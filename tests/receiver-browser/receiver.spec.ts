import { test, expect } from '@playwright/test'
import { mockMapTiles } from '../mapTiles'
import { execFileSync } from 'node:child_process'

// Sends only to the dedicated loopback test socket, never station multicast.
function packet(expression: string, count = 1) {
 execFileSync('.venv/bin/python', ['-c', `import socket\nfrom backend.tests.fixtures import status, decode, header\ns=socket.socket(socket.AF_INET,socket.SOCK_DGRAM)\nfor _ in range(${count}): s.sendto(${expression},('127.0.0.1',18238))\ns.close()`])
}

test('actual local UDP drives two browsers and bounded interactive diagnostics', async ({ browser, request, baseURL }) => {
 const a = await browser.newContext(), b = await browser.newContext()
 const first = await a.newPage(), second = await b.newPage()
 await mockMapTiles(first); await mockMapTiles(second)
 const errors: string[] = []
 first.on('pageerror', e => errors.push(e.message)); second.on('pageerror', e => errors.push(e.message))
 await first.goto(baseURL!); await second.goto(baseURL!)
 await expect(first.getByRole('heading', { name: 'Waiting for a WSJT-X selection' })).toBeVisible()
 packet("status(call='N0BASE',rig='Radio A')"); packet("status(call='N1BASE',rig='Radio B')")
 await expect.poll(async () => (await (await request.get('/api/snapshot')).json()).rigs.length).toBe(2)
 expect((await (await request.get('/api/snapshot')).json()).history).toEqual([])
 packet("status(call='W1ACT',rig='Radio A')")
 await expect(second.getByTestId('focused-call')).toHaveText('W1ACT')
 packet("status(call='K2ACT',rig='Radio B')")
 await expect(first.getByTestId('focused-call')).toHaveText('K2ACT')
 const before = (await (await request.get('/api/snapshot')).json()).history
 await second.getByTestId('history-W1ACT').click()
 await expect(first.getByTestId('focused-call')).toHaveText('W1ACT')
 const after = (await (await request.get('/api/snapshot')).json()).history
 expect(after.map(({ browsedAt, ...entry }: any) => entry)).toEqual(before)
 packet("decode(rig='Radio A')")
 packet("status(call='',rig='Radio B')")
 await expect(first.getByTestId('focused-call')).toHaveText('W1ACT')
 await b.setOffline(true); await second.evaluate(() => window.dispatchEvent(new Event('offline')))
 packet("status(call='K3ACT',rig='Radio A')")
 await expect(first.getByTestId('focused-call')).toHaveText('K3ACT')
 await b.setOffline(false); await second.evaluate(() => window.dispatchEvent(new Event('online')))
 await expect(second.getByTestId('focused-call')).toHaveText('K3ACT')
 await expect(second.getByText('Available operator and license information appears in Details.', { exact: false })).toBeVisible()
 await expect(second.getByText('History is disabled · worked-before status unknown')).toBeVisible()
 await first.getByRole('button', { name: 'Diagnostics', exact: true }).click()
 await expect(first.locator('.instance-table tbody tr')).toHaveCount(2)
 await expect(first.locator('.instance-table')).toContainText('127.0.0.1:')
 packet("header(kind=0,rig='Radio A')")
 await first.getByLabel('Heard instance').selectOption('Radio A')
 await first.getByLabel('Radio activity').selectOption('signals')
 await expect(first.locator('.packet-table')).toContainText('CQ W7DEMO AA00')
 await expect(first.locator('.packet-table')).not.toContainText('Radio B')
 await expect(first.locator('.packet-table')).not.toContainText('Heartbeat')
 await first.getByLabel('Radio activity').selectOption('connection')
 await expect(first.locator('.packet-table')).toContainText('Heartbeat · check-in')
 await expect(first.locator('.packet-table')).toContainText('WSJT-X is checking in')
 await first.getByLabel('Radio activity').selectOption('radio')
 await expect(first.locator('.packet-table')).toContainText('Status · radio state')
 await expect(first.locator('.packet-table')).toContainText('14.074000 MHz')
 await first.getByLabel('Radio activity').selectOption('all')
 await first.getByLabel('Heard instance').selectOption('')
 await first.getByRole('button', { name: 'Pause display' }).click()
 const frozen = await first.locator('.packet-table tbody').textContent()
 packet("decode(rig='Radio A')", 80)
 await expect.poll(async () => (await (await request.get('/api/snapshot')).json()).counters.decodes).toBeGreaterThan(50)
 expect(await first.locator('.packet-table tbody').textContent()).toBe(frozen)
 await first.getByRole('button', { name: 'Clear diagnostics' }).click()
 await expect(first.locator('.packet-table')).toContainText('No matching packets')
 await expect(second.getByTestId('focused-call')).toHaveText('K3ACT')
 await first.getByRole('button', { name: 'Resume display' }).click()
 packet("header(kind=999,rig='Radio A') + b'unknown payload'")
 packet("b'broken'")
 packet("status(call='K3ACT',rig='Radio A')")
 await expect(first.locator('.packet-table tbody tr')).toHaveCount(3)
 await first.getByLabel('Packet filter').selectOption('errors')
 await expect(first.locator('.packet-table')).toContainText('invalid magic')
 await expect(first.locator('.packet-table tbody tr')).toHaveCount(1)
 await first.getByLabel('Packet filter').selectOption('unknown')
 await first.getByRole('button', { name: /Inspect packet/ }).click()
 await expect(first.getByRole('region', { name: 'Packet details' })).toContainText('Payload is not interpreted')
 await first.getByText('Original datagram · Base64').click()
 await expect(first.locator('.packet-detail details pre')).not.toHaveText('')
 await first.getByLabel('Packet filter').selectOption('1')
 await first.getByRole('button', { name: /Inspect packet/ }).click()
 await expect(first.locator('.packet-detail')).toContainText('"dxCall": "K3ACT"')
 await first.getByLabel('Packet filter').selectOption('all')
 await first.screenshot({ path: 'test-results/step1-diagnostics.png', fullPage: true })
 await first.getByRole('button', { name: 'Settings', exact: true }).click()
 await first.getByRole('tab', { name: 'Radio receiver', exact: true }).click()
 const originalPreferences=(await (await request.get('/api/snapshot')).json()).preferences
 await first.getByLabel('Diagnostic retention (packets)').fill('150')
 await first.getByRole('tab',{name:'Workspace',exact:true}).click()
 await expect(first.getByRole('tabpanel')).toHaveCount(1)
 await first.getByLabel('Saved appearance').selectOption(originalPreferences.appearance === 'dark' ? 'light' : 'dark')
 await first.getByRole('tab',{name:'Radio receiver',exact:true}).click()
 await expect(first.getByLabel('Diagnostic retention (packets)')).toHaveValue('150')
 await first.getByLabel('Diagnostic retention (packets)').fill('100')
 await first.getByRole('button', { name: 'Save receiver settings' }).click()
 await expect(first.getByText('Saved to config.toml and applied now.', { exact: false })).toBeVisible()
 expect((await (await request.get('/api/snapshot')).json()).preferences).toEqual(originalPreferences)
 packet("status(call='K4ACT',rig='Radio A')")
 await expect(second.getByTestId('focused-call')).toHaveText('K4ACT') // Retention edit didn't reset baseline.
 await first.getByRole('button', { name: 'Restart receiver', exact: true }).click()
 await expect(first.getByText('Receiver restarted.', { exact: false })).toBeVisible()
 packet("status(call='K5BASE',rig='Radio A')")
 await expect.poll(async () => (await (await request.get('/api/snapshot')).json()).rigs.find((r: any) => r.id === 'Radio A')?.call).toBe('K5BASE')
 expect((await (await request.get('/api/snapshot')).json()).call).toBe('K4ACT')
 packet("status(call='K6ACT',rig='Radio A')")
 await expect(second.getByTestId('focused-call')).toHaveText('K6ACT')
 await first.getByLabel('Enable UDP receiver').uncheck()
 await first.getByRole('button', { name: 'Save receiver settings' }).click()
 await expect.poll(async () => (await (await request.get('/api/snapshot')).json()).receiver.status).toBe('disabled')
 await expect(second.getByTestId('focused-call')).toHaveText('K6ACT')
 await first.screenshot({ path: 'test-results/step1-settings.png', fullPage: true })
 await first.setViewportSize({ width: 390, height: 844 })
 expect(await first.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
 expect(errors).toEqual([])
 await a.close(); await b.close()
})
