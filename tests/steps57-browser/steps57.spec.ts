test('forwarding settings dispatch raw packets, filter rigs, disable and resume with logging off',async({page,request,baseURL})=>{
 const sink=dgram.createSocket('udp4'),received:Buffer[]=[]
 sink.on('message',data=>received.push(data));await new Promise<void>(resolve=>sink.bind(0,'127.0.0.1',()=>resolve()))
 const address=sink.address();if(typeof address==='string')throw new Error('UDP socket address missing')
 try {
  await mockMapTiles(page);await page.goto(baseURL!);await page.getByRole('button',{name:'Settings',exact:true}).click()
  await page.getByRole('tab',{name:'UDP forwarding',exact:true}).click()
  const form=page.getByRole('form',{name:'UDP forwarding settings',exact:true})
  await form.getByRole('button',{name:'Add UDP destination',exact:true}).click()
  const destination=form.locator('.forwarding-destination').first()
  await destination.getByLabel('Name',{exact:true}).fill('Loopback browser collector')
  await destination.getByLabel('UDP port',{exact:true}).fill(String(address.port))
  await destination.getByLabel('Enable destination',{exact:true}).check()
  await destination.getByLabel('Rig filters',{exact:false}).fill('Browser rig A')
  await form.getByRole('button',{name:'Save UDP forwarding settings',exact:true}).click()
  await expect(form).toContainText('UDP forwarding settings saved.')
  await expect.poll(async()=>(await(await request.get('/api/forwarding')).json()).destinations[0].status).toBe('ready')
  send(selected('K4FORWARD'));await expect.poll(()=>received.length).toBe(1)
  expect(received[0]!.readUInt32BE(0)).toBe(0xadbccbda);expect(received[0]!.readUInt32BE(8)).toBe(1)
  send("decode(rig='Other rig')")
  await expect.poll(async()=>(await(await request.get('/api/forwarding')).json()).destinations[0].filtered).toBeGreaterThan(0)
  expect(received.length).toBe(1)
  await destination.getByLabel('Enable destination',{exact:true}).uncheck()
  await form.getByRole('button',{name:'Save UDP forwarding settings',exact:true}).click();await expect(form).toContainText('UDP forwarding settings saved.')
  send(selected('K5STOP'))
  await expect.poll(async()=>(await(await request.get('/api/snapshot')).json()).call).toBe('K5STOP')
  expect(received.length).toBe(1)
  await destination.getByLabel('Enable destination',{exact:true}).check()
  await form.getByRole('button',{name:'Save UDP forwarding settings',exact:true}).click();await expect(form).toContainText('UDP forwarding settings saved.')
  await expect.poll(async()=>(await(await request.get('/api/forwarding')).json()).destinations[0].status).toBe('ready')
  send(selected('K6RESUME'));await expect.poll(()=>received.length).toBe(2)
  expect((await(await request.get('/api/snapshot')).json()).qso.config.logging_enabled).toBe(false)
  await page.screenshot({path:'test-results/steps57-forwarding-settings.png',fullPage:true})
 }finally{sink.close()}
})
