import { test, expect } from '@playwright/test'
import { execFileSync } from 'node:child_process'
function packet(call: string) {
 execFileSync('.venv/bin/python', ['-c', `import socket\nfrom backend.tests.fixtures import status\ns=socket.socket(socket.AF_INET,socket.SOCK_DGRAM)\ns.sendto(status(call='${call}',rig='Enrichment fixture'),('127.0.0.1',18239))\ns.close()`])
}
test('enrichment arrives in two browsers, settings retain provenance, missing QRZ stays explicit', async ({ browser, request, baseURL }) => {
 const first = await browser.newPage(), second = await browser.newPage()
 const errors: string[] = []
 first.on('pageerror', error => errors.push(error.message)); second.on('pageerror', error => errors.push(error.message))
 await first.goto(baseURL!); await second.goto(baseURL!)
 packet('K0BASE'); await expect.poll(async () => (await (await request.get('/api/snapshot')).json()).rigs.length).toBe(1)
 packet('K1ACT')
 const card = first.getByRole('region', { name: 'Station enrichment' })
 await expect(card.locator('.enrichment-summary').getByText('United States', { exact: true })).toBeVisible()
 await expect(second.getByRole('region', { name: 'Station enrichment' }).locator('.enrichment-summary').getByText('United States', { exact: true })).toBeVisible()
 packet('DL1ACT'); await expect(first.getByTestId('focused-call')).toHaveText('DL1ACT')
 await expect(card.locator('.enrichment-summary').getByText('Fed. Rep. of Germany', { exact: true })).toBeVisible()
 await card.getByText(/All returned fields/).click()
 await expect(card.locator('table')).toContainText('Country-files.com')
 const before = (await (await request.get('/api/snapshot')).json()).history
 await second.getByTestId('history-K1ACT').click()
 await expect(card.locator('.enrichment-summary').getByText('United States', { exact: true })).toBeVisible()
 expect((await (await request.get('/api/snapshot')).json()).history.map(({ browsedAt, ...entry }: any) => entry)).toEqual(before)
 const overview = await first.locator('.station-overview').boundingBox(), enrichment = await card.boundingBox()
 expect(enrichment!.y).toBeGreaterThanOrEqual(overview!.y + overview!.height)
 await first.screenshot({ path: 'test-results/step2-enrichment.png', fullPage: true })
 await first.setViewportSize({ width: 390, height: 844 })
 expect(await first.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
 await first.setViewportSize({ width: 1440, height: 1000 })
 await first.getByRole('button', { name: 'Settings', exact: true }).click()
 const settings = first.getByRole('form', { name: 'Enrichment settings' })
 await settings.getByLabel('Add QRZ XML callbook details').check()
 await expect(settings.getByLabel('QRZ XML password', { exact: true })).toHaveAttribute('type', 'password')
 await settings.getByRole('button', { name: 'Save enrichment settings' }).click()
 await expect.poll(async () => (await (await request.get('/api/snapshot')).json()).enrichment.result.providers?.qrz?.status).toBe('error')
 const snapshot = (await (await request.get('/api/snapshot')).json())
 expect(snapshot.enrichment.result.fields.country).toBe('United States')
 expect(snapshot.enrichment.config).not.toHaveProperty('qrz_password')
 await settings.getByLabel('Station grid override (optional)').fill('FN31')
 await settings.getByRole('button', { name: 'Save enrichment settings' }).click()
 await expect.poll(async () => (await (await request.get('/api/snapshot')).json()).enrichment.result.stationGrid).toBe('FN31')
 await settings.getByLabel('Enable enrichment for radio selections').uncheck()
 await settings.getByRole('button', { name: 'Save enrichment settings' }).click()
 await expect.poll(async () => (await (await request.get('/api/snapshot')).json()).enrichment.result.status).toBe('disabled')
 expect((await (await request.get('/api/snapshot')).json()).receiver.status).toBe('listening')
 await first.setViewportSize({ width: 390, height: 844 })
 expect(await first.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
 await first.screenshot({ path: 'test-results/step2-settings.png', fullPage: true })
 expect(errors).toEqual([])
 await first.close(); await second.close()
})

test('QRZ photos appear beside the callsign and as shared history thumbnails', async ({ browser, request, baseURL }) => {
 const context = await browser.newContext()
 await context.route('https://photos.example.invalid/**', route => route.fulfill({
  contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="320" height="240"><rect width="320" height="240" fill="#397b67"/><circle cx="160" cy="90" r="45" fill="#dceee5"/><path d="M70 240v-30a90 90 0 0 1 180 0v30" fill="#dceee5"/></svg>'
 }))
 const first = await context.newPage(), second = await context.newPage()
 await first.goto(baseURL!); await second.goto(baseURL!)
 const saved = await request.put('/api/enrichment', { data: { enabled: true, qrz_enabled: true, qrz_username: 'fixture-user', qrz_password: 'fixture-password' } })
 expect(saved.ok()).toBe(true)
 const photo = first.locator('.station-overview > .station-photo img')
 packet('K0BASE')
 await expect.poll(async () => (await (await request.get('/api/snapshot')).json()).rigs.find((rig: any) => rig.id === 'Enrichment fixture')?.call).toBe('K0BASE')
 packet('K1ACT')
 await expect(photo).toHaveAttribute('alt', 'QRZ profile for K1ACT')
 packet('K7PIC')
 await expect(photo).toHaveAttribute('alt', 'QRZ profile for K7PIC')
 await expect.poll(() => photo.evaluate((img: HTMLImageElement) => img.naturalWidth)).toBeGreaterThan(0)
 await expect(second.getByTestId('history-K7PIC').getByRole('img')).toHaveAttribute('alt', 'QRZ profile for K7PIC')
 const large = await photo.boundingBox(), small = await first.getByTestId('history-K7PIC').locator('img').boundingBox()
 expect(large!.width).toBeGreaterThan(180)
 expect(small!.width).toBeLessThanOrEqual(60)
 expect(large!.width).toBeGreaterThan(small!.width * 3)
 const before = (await (await request.get('/api/snapshot')).json()).history
 await second.getByTestId('history-K1ACT').click()
 await expect(photo).toHaveAttribute('alt', 'QRZ profile for K1ACT')
 await expect(first.getByTestId('history-K7PIC').locator('img')).toHaveAttribute('alt', 'QRZ profile for K7PIC')
 expect((await (await request.get('/api/snapshot')).json()).history.map(({ browsedAt, ...entry }: any) => entry)).toEqual(before.map(({ browsedAt, ...entry }: any) => entry))
 await first.reload()
 await expect(first.getByTestId('history-K7PIC').locator('img')).toBeVisible()
 await first.screenshot({ path: 'test-results/step2-photos.png', fullPage: true })
 await first.setViewportSize({ width: 900, height: 1000 })
 expect(await first.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
 await first.setViewportSize({ width: 390, height: 844 })
 expect(await first.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
 packet('K2NPH')
 await expect(first.getByTestId('focused-call')).toHaveText('K2NPH')
 await expect(first.getByTestId('history-K2NPH').getByRole('img')).toHaveAttribute('aria-label', 'No profile photo available for K2NPH')
 await context.close()
})
