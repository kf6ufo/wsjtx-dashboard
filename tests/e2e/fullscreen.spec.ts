test('unsupported and denied full screen leave the display usable', async ({ page }) => {
 await page.addInitScript(() => Object.defineProperty(document, 'fullscreenEnabled', { configurable: true, value: false }))
 await page.goto('/?mode=demo')
 await page.getByRole('button', { name: 'Full screen', exact: true }).click()
 await expect(page.locator('.connection-note[role="status"]')).toContainText('Full screen is unavailable')
 await expect(page.locator('.brand')).toBeVisible()
 await page.evaluate(() => {
  Object.defineProperty(document, 'fullscreenEnabled', { configurable: true, value: true })
  document.documentElement.requestFullscreen = () => Promise.reject(new Error('Denied'))
 })
 await page.getByRole('button', { name: 'Full screen', exact: true }).click()
 await expect(page.locator('.connection-note[role="status"]')).toContainText('The browser could not change full screen')
 await expect(page.getByRole('button', { name: 'Full screen', exact: true })).toBeEnabled()
 await expect(page.locator('.brand')).toBeVisible()
})
