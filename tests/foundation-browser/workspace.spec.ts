import { test, expect } from '@playwright/test'

test('built workspace synchronizes windows, preserves browsing provenance and recovers missed updates', async ({ browser, baseURL }) => {
 const a = await browser.newContext(), b = await browser.newContext()
 const first = await a.newPage(), second = await b.newPage()
 const errors: string[] = []
 first.on('pageerror', error => errors.push(error.message)); second.on('pageerror', error => errors.push(error.message))
 await first.goto(baseURL!); await second.goto(baseURL!)
 await expect(first.locator('.demo-status')).toContainText('connected')
 await expect(second.locator('.demo-status')).toContainText('connected')
 await first.getByRole('button', { name: 'Demo tools', exact: true }).click()
 await first.getByLabel('Callsign', { exact: true }).selectOption('DL1DEMO')
 await first.getByLabel('Simulated radio', { exact: true }).selectOption('WSJT-X - Field')
 await first.getByRole('button', { name: 'Simulate a station selection', exact: true }).click()
 await expect(second.getByTestId('focused-call')).toHaveText('DL1DEMO')
 const snapshot = await (await first.request.get(baseURL! + '/api/snapshot')).json()
 await second.getByTestId('history-JA2HDE').click()
 await expect(first.getByTestId('focused-call')).toHaveText('JA2HDE')
 const browsed = await (await first.request.get(baseURL! + '/api/snapshot')).json()
 expect(browsed.history.map(({ browsedAt, ...entry }: any) => entry)).toEqual(snapshot.history.map(({ browsedAt, ...entry }: any) => entry))
 await b.setOffline(true)
 await second.evaluate(() => window.dispatchEvent(new Event('offline')))
 await expect(second.locator('.connection-note')).toContainText('stale')
 await first.getByTestId('history-VK3DEMO').click()
 await expect(first.getByTestId('focused-call')).toHaveText('VK3DEMO')
 await b.setOffline(false)
 await second.evaluate(() => window.dispatchEvent(new Event('online')))
 await expect(second.getByTestId('focused-call')).toHaveText('VK3DEMO')
 await expect(second.getByText('Lookup complete · 0 sample contacts')).toBeVisible()
 await first.getByRole('button', { name: 'Settings', exact: true }).click()
 await first.getByLabel('Station title').fill('Step 0 review desk')
 await second.getByTestId('history-DL1DEMO').click()
 await expect(first.getByLabel('Station title')).toHaveValue('Step 0 review desk')
 await first.getByLabel('Saved appearance').selectOption('light')
 await first.getByRole('button', { name: 'Save workspace settings' }).click()
 await expect(first.getByRole('form', { name: 'Workspace preferences' }).getByRole('status')).toContainText('Saved on this server')
 await expect(second.locator('.workspace-bar h2')).toHaveText('Step 0 review desk')
 await expect(second.locator('.app-shell')).toHaveClass(/theme-light/)
 await second.reload()
 await expect(second.getByTestId('focused-call')).toHaveText('DL1DEMO')
 await second.getByRole('button', { name: 'Diagnostics', exact: true }).click()
 await expect(second.getByRole('heading', { name: 'Diagnostics', exact: true })).toBeVisible()
 await expect(second.getByText('No received instances yet. Enable/configure the receiver in Settings.')).toBeVisible()
 await second.screenshot({ path: 'test-results/step0-diagnostics.png', fullPage: true })
 await second.getByRole('button', { name: 'Station', exact: true }).click()
 await second.getByTestId('history-JA2HDE').click()
 await expect(second.locator('tbody tr')).toHaveCount(24)
 await second.screenshot({ path: 'test-results/step0-light.png', fullPage: true })
 await second.getByRole('button', { name: 'Theme: Light' }).click()
 await second.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
 await second.screenshot({ path: 'test-results/step0-dark.png', fullPage: true })
 await second.setViewportSize({ width: 390, height: 844 })
 expect(await second.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
 await second.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
 await second.screenshot({ path: 'test-results/step0-mobile.png', fullPage: true })
 expect(errors).toEqual([])
 await a.close(); await b.close()
})
